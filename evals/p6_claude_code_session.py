"""Phase 6 acceptance: Claude Code, with only the Stockroom MCP server and skill, answers eval questions.

    python -m evals.p6_claude_code_session       # needs ANTHROPIC_API_KEY and the `claude` CLI; ~$1

Each question runs in a fresh headless Claude Code session (`claude -p`):
- MCP servers: only this repo's `.mcp.json` (`--strict-mcp-config`).
- Built-in tools: only `Skill` (`--tools Skill`). No Bash, Read or Write, so every number has to come
  through the MCP server and its guards, not from opening the DuckDB files.
- The question is sent as `/stockroom-analyst <question>`, so the project skill is loaded.
- The Stockroom tools are pre-allowed with `--allowedTools`, which stands in for a user clicking
  "allow". Headless mode can't prompt.
- Drafts go to a scratch app.duckdb (`STOCKROOM_APP_DB`), not the real one.

Questions and expected answers come from `evals/questions.jsonl` (computed from ground truth). They are
scored by the same deterministic scorers as the P5 eval. Writes docs/results/claude_code_session_p6.md.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import subprocess
import time
from pathlib import Path
from typing import Any

from evals.run import FORMAT
from evals.scoring import score
from stockroom import config

OUT = config.ROOT / "docs" / "results" / "claude_code_session_p6.md"
RUN_DIR = config.RUNS_DIR / "p6"
IDS = ["T1-29", "T4-24", "T2-01", "T3-01", "T3-14", "T4-01", "T4-06", "T4-18"]
MODEL = os.environ.get("STOCKROOM_MODEL", config.MODEL)
STOCKROOM_TOOLS = [f"mcp__stockroom__{n}" for n in (
    "describe_data", "run_sql", "detect_anomalies", "explain_variance", "forecast_demand", "draft_reorder"
)]  # fmt: skip


def claude_cmd(prompt: str) -> list[str]:
    return [
        "claude", "-p", prompt,
        "--model", MODEL,
        "--setting-sources", "project",  # this repo's skills; not the machine's user settings
        "--mcp-config", str(config.ROOT / ".mcp.json"), "--strict-mcp-config",
        "--tools", "Skill",
        "--allowedTools", ",".join(STOCKROOM_TOOLS),
        "--no-chrome", "--no-session-persistence",
        "--max-budget-usd", "0.60",
        "--output-format", "stream-json", "--verbose",
    ]  # fmt: skip


def run_one(q: dict[str, Any], env: dict[str, str]) -> dict[str, Any]:
    t0 = time.monotonic()
    proc = subprocess.run(
        claude_cmd(f"/stockroom-analyst {q['question']}{FORMAT}"),
        cwd=config.ROOT, env=env, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=600,
    )  # fmt: skip
    events = [json.loads(line) for line in proc.stdout.splitlines() if line.startswith("{")]
    (RUN_DIR / f"{q['id']}.jsonl").write_text(proc.stdout)
    init = next((e for e in events if e.get("type") == "system" and e.get("subtype") == "init"), {})
    final = next((e for e in reversed(events) if e.get("type") == "result"), {})
    calls, texts = [], []
    for e in events:
        if e.get("type") == "assistant":
            for c in e["message"]["content"]:
                if c["type"] == "tool_use":
                    calls.append({"name": c["name"], "input": c["input"]})
                elif c["type"] == "text":
                    texts.append(c["text"])
    answer = final.get("result") or (texts[-1] if texts else "")
    ok, why, line = score(q, answer)
    return {
        **q,
        "answer": answer,
        "answer_line": line,
        "correct": ok,
        "reason": why,
        "tool_calls": calls,
        "tools_available": init.get("tools", []),
        "skill_loaded": "stockroom-analyst" in (init.get("skills") or []),
        "mcp_status": {s["name"]: s["status"] for s in init.get("mcp_servers", [])},
        "cost_usd": float(final.get("total_cost_usd") or 0),
        "turns": final.get("num_turns"),
        "latency_s": round(time.monotonic() - t0, 1),
        "exit_code": proc.returncode,
        "stderr_tail": proc.stderr.strip().splitlines()[-3:],
    }


def claude_version() -> str:
    return subprocess.run(["claude", "--version"], capture_output=True, text=True).stdout.strip()


def cell(x: Any) -> str:
    return str(x).replace("|", "\\|").replace("\n", " ")


def render(rows: list[dict[str, Any]], version: str) -> str:
    passed = sum(r["correct"] for r in rows)
    cost = sum(r["cost_usd"] for r in rows)
    outside = sorted(
        {c["name"] for r in rows for c in r["tool_calls"] if not c["name"].startswith("mcp__stockroom__")}
    )
    available = sorted(set().union(*(r["tools_available"] for r in rows)))
    lines = [
        "# Phase 6: Claude Code + Stockroom MCP server",
        "",
        "Generated by `python -m evals.p6_claude_code_session`. Do not edit by hand.",
        "",
        (
            f"*Run {dt.date.today()} with {version}, model `{MODEL}`. Each question ran in a fresh headless session: "
            '`claude -p "/stockroom-analyst <question>" --mcp-config .mcp.json --strict-mcp-config --tools Skill ...`. '
            "Questions, expected answers and scorers come from the P5 eval (`evals/questions.jsonl`, ground truth).*"
        ),
        "",
        (
            f"**{passed}/{len(rows)} correct**, ${cost:.2f} total. Tools the model could call: "
            f"{', '.join(f'`{t}`' for t in available)}. "
            f"Tools it called outside the MCP server: {', '.join(outside) if outside else 'none'}."
        ),
        "",
        "| Id | Question | Expected | Claude Code's ANSWER | Correct | MCP tool calls | $ | Time |",
        "|---|---|---|---|---|---|---:|---:|",
    ]
    for r in rows:
        mcp_calls = [
            c["name"].removeprefix("mcp__stockroom__") for c in r["tool_calls"] if c["name"] != "Skill"
        ]
        lines.append(
            f"| {r['id']} | {cell(r['question'])} | {cell(r['expected'])} | {cell(r['answer_line'] or '(none)')} | "
            f"{'✅' if r['correct'] else '❌ ' + cell(r['reason'])} | {', '.join(mcp_calls)} | "
            f"{r['cost_usd']:.3f} | {r['latency_s']:.0f}s |"
        )
    lines += ["", "## Transcripts", ""]
    for r in rows:
        lines += [f"### {r['id']}: {r['question']}", ""]
        for c in r["tool_calls"]:
            arg = json.dumps(c["input"])
            if "query" in c["input"]:
                lines += [f"- `{c['name']}`", "", "```sql", c["input"]["query"].strip(), "```", ""]
            else:
                lines.append(f"- `{c['name']}` `{arg[:300]}`")
        lines += [
            "",
            "**Answer:**",
            "",
            *[f"> {x}" if x else ">" for x in r["answer"].strip().splitlines()],
            "",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    RUN_DIR.mkdir(parents=True, exist_ok=True)
    app_db = RUN_DIR / "app.duckdb"
    app_db.unlink(missing_ok=True)
    env = {**os.environ, "STOCKROOM_APP_DB": str(app_db)}
    qs = {
        q["id"]: q
        for q in map(json.loads, Path(config.ROOT / "evals" / "questions.jsonl").read_text().splitlines())
    }
    rows = []
    for qid in IDS:
        r = run_one(qs[qid], env)
        rows.append(r)
        print(
            f"{'PASS' if r['correct'] else 'FAIL'} {qid} ${r['cost_usd']:.3f} {r['latency_s']}s  {r['answer_line']}"
        )
    (RUN_DIR / "results.jsonl").write_text("".join(json.dumps(r, default=str) + "\n" for r in rows))
    OUT.write_text(render(rows, claude_version()))
    print(f"wrote {OUT.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
